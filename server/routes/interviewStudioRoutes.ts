router.get("/interview-studio/templates", authenticateToken, asyncHandler(async (_req, res) => {
  const readiness = interviewReadiness();
  if (!readiness.practiceEnabled) {
    return res.status(503).json({ message: "Interview Studio is not enabled in this environment", code: "INTERVIEW_STUDIO_DISABLED" });
  }
  const templates = await db.select().from(interviewStudioTemplates).where(and(
    eq(interviewStudioTemplates.state, "published"),
    eq(interviewStudioTemplates.isCurrent, true),
  )).orderBy(interviewStudioTemplates.title);
  const items = templates.map((template) => {
    const blueprint = asBlueprint(template.blueprint, template.blueprintHash);
    const supportedModes = [...template.supportedModes].sort();
    const allowedModes = [...blueprint.allowedModes].sort();
    if (JSON.stringify(supportedModes) !== JSON.stringify(allowedModes)) {
      throw Object.assign(new Error("Interview template mode snapshot is inconsistent"), { status: 500 });
    }
    return {
      id: template.id,
      key: template.templateKey,
      templateKey: template.templateKey,
      version: template.version,
      title: template.title,
      targetRole: blueprint.role,
      description: template.summary,
      summary: template.summary,
      skills: blueprint.skills,
      difficulty: blueprint.level,
      durationMinutes: blueprint.estimatedDurationMinutes,
      availableModes: template.supportedModes.filter((mode) => mode === "practice" || readiness.verifiedEnabled),
      ...summarizeInterviewStudioBlueprintForCatalog(blueprint),
    };
  });
  res.setHeader("Cache-Control", "private, no-store");
  res.json({ items });
}));

