function nowPlusDays(days: number) {
  return new Date(Date.now() + days * 86_400_000);
}

function sha256(value: string) {
  return crypto.createHash("sha256").update(value, "utf8").digest("hex");
}

function asBlueprint(value: unknown, expectedHash?: string) {
  const blueprint = interviewStudioBlueprintSchema.parse(value);
  if (expectedHash && sha256(canonicalizeInterviewStudioBlueprint(blueprint)) !== expectedHash) {
    throw Object.assign(new Error("Interview blueprint integrity check failed"), {
      code: "INTERVIEW_BLUEPRINT_INTEGRITY_FAILED",
      status: 500,
    });
  }
  return blueprint;
}

function findBlueprintItem(blueprint: InterviewStudioBlueprint, itemKey: string) {
  return blueprint.items.find((item) => item.key === itemKey);
}

