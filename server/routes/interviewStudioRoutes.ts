function interviewReadiness() {
  const base = getInterviewStudioReadiness(process.env);
  const aiEvaluationEnabled = isInterviewAiEnabled(process.env);
  const codeRunnerEnabled = isCodeRunnerEnabled(process.env);
  const voiceTranscriptionEnabled = isInterviewTranscriptionEnabled(process.env);
  const evaluationWorkerEnabled = getInterviewStudioEvaluationWorkerConfig(process.env).enabled;
  return {
    practiceEnabled: base.practiceReady,
    // The data model already fails closed for verified evidence, but its
    // resumable private recording, human-review and expiring playback APIs are
    // intentionally not part of this private-practice release.
    verifiedEnabled: false,
    aiEvaluationEnabled,
    voiceTranscriptionEnabled,
    codeRunnerEnabled,
    recordingEnabled: false,
    evaluationWorkerEnabled,
    consentVersion: CONSENT_VERSION,
    limitations: [
      ...(!aiEvaluationEnabled ? ["ai_evaluation_not_configured"] : []),
      ...(!codeRunnerEnabled ? ["isolated_code_runner_not_configured"] : []),
      ...(!evaluationWorkerEnabled ? ["evaluation_worker_disabled"] : []),
      "verified_interview_workflow_not_released",
      "practice_sessions_are_private",
      "camera_and_screen_are_readiness_checks_only",
    ],
  };
}

