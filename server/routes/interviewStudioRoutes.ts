router.post("/interview-studio/sessions", authenticateToken, writeLimiter, asyncHandler(async (req, res) => {
  const parsed = createSessionBodySchema.safeParse(req.body);
  if (!parsed.success) {
    return res.status(400).json({ message: "Review the interview setup and consent choices", errors: parsed.error.flatten() });
  }
  const readiness = interviewReadiness();
  if (!readiness.practiceEnabled) {
    return res.status(503).json({ message: "Interview Studio is not enabled", code: "INTERVIEW_STUDIO_DISABLED" });
  }
  if (parsed.data.mode === "verified" && !readiness.verifiedEnabled) {
    return res.status(409).json({
      message: "Verified interviews are not open yet. Private practice is available now.",
      code: "VERIFIED_INTERVIEW_NOT_READY",
    });
  }
  if (parsed.data.consent.consentVersion !== CONSENT_VERSION) {
    return res.status(409).json({ message: "The interview disclosure has changed. Review it again before starting.", code: "INTERVIEW_CONSENT_OUTDATED" });
  }
  const templateCondition = parsed.data.templateId
    ? eq(interviewStudioTemplates.id, parsed.data.templateId)
    : eq(interviewStudioTemplates.templateKey, parsed.data.templateKey!);
  const [template] = await db.select().from(interviewStudioTemplates).where(and(
    templateCondition,
    eq(interviewStudioTemplates.state, "published"),
    eq(interviewStudioTemplates.isCurrent, true),
  )).limit(1);
  if (!template) return res.status(404).json({ message: "Interview template not found" });
  if (!template.supportedModes.includes(parsed.data.mode)) {
    return res.status(409).json({ message: "This template does not support the selected interview mode" });
  }

  const blueprint = asBlueprint(template.blueprint, template.blueprintHash);
  const now = new Date();
  const sessionId = crypto.randomUUID();
  const [session] = await db.insert(interviewStudioSessions).values({
    id: sessionId,
    templateId: template.id,
    templateKey: template.templateKey,
    templateVersion: template.version,
    userId: req.user!.userId,
    mode: parsed.data.mode,
    status: "ready",
    blueprintSnapshot: blueprint,
    blueprintHash: template.blueprintHash,
    consentSnapshot: {
      policyVersion: CONSENT_VERSION,
      acknowledgedAt: now.toISOString(),
      aiEvaluation: parsed.data.consent.aiProcessing,
      microphoneTranscription: parsed.data.consent.microphone,
      // Practice camera/screen are local readiness checks, never recordings.
      cameraRecording: false,
      screenRecording: false,
      recruiterSharing: false,
    },
    permissionSnapshot: {
      capturedAt: now.toISOString(),
      camera: { required: parsed.data.consent.camera, state: "not_requested" },
      microphone: { required: parsed.data.consent.microphone, state: "not_requested" },
      screen: { required: parsed.data.consent.screen, state: "not_requested" },
    },
    serverDeadlineAt: null,
    evaluationStatus: parsed.data.consent.aiProcessing ? "pending" : "not_requested",
    retentionUntil: nowPlusDays(PRACTICE_RETENTION_DAYS),
  }).returning();

  await audit({
    action: "interview_studio.session_created",
    userId: req.user!.userId,
    actorRole: "learner",
    resourceType: "interview_studio_session",
    resourceId: session.id,
    metadata: {
      templateKey: template.templateKey,
      templateVersion: template.version,
      mode: parsed.data.mode,
      aiEvaluationConsent: parsed.data.consent.aiProcessing,
      microphoneTranscriptionConsent: parsed.data.consent.microphone,
    },
    req,
  });
  res.status(201).json(await sessionPayload(session));
}));

